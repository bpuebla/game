const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const {JSDOM}=require(process.env.MORTI_JSDOM || 'jsdom');
const html=fs.readFileSync('index.html','utf8');
assert.equal(html,fs.readFileSync('dist/index.html','utf8'),'Both entrypoints must open the same game');
const {window}=new JSDOM(html,{url:'file:///tmp/morti-moved-to-another-folder/index.html'});
const doc=window.document;
assert.equal(doc.querySelectorAll('script[src],link[rel="stylesheet"]').length,0,'No external scripts or stylesheets');
assert.equal(doc.querySelectorAll('script[type="module"]').length,0,'No file:// module loading');
assert.ok(doc.querySelector('style').textContent.includes('.game-shell'),'Game styling embedded');
assert.ok(!doc.querySelector('style').textContent.includes('@import'),'No remote font dependency');
assert.equal(window.getComputedStyle(doc.querySelector('.stage')).position,'relative','Game layout styles actually parse and apply');
assert.equal(window.getComputedStyle(doc.querySelector('#finish-screen')).display,'none','Completion screen initially hidden by CSS');
assert.equal(window.getComputedStyle(doc.querySelector('.overlay')).position,'absolute','Overlay styles apply');
const scripts=[...doc.querySelectorAll('script')];
assert.equal(scripts.length,3);
for(const [i,script]of scripts.entries())new vm.Script(script.textContent,{filename:`inline-${i}.js`});
assert.ok(scripts[2].textContent.includes('data:image/png;base64,'),'Artwork embedded');
assert.ok(doc.querySelector('#boot-error'),'Startup errors visible');
console.log('PASS: both entrypoints identical; stylesheet parses and applies; initial overlays correct; all three inline scripts compile; artwork embedded; no external runtime files needed.');
window.close();
